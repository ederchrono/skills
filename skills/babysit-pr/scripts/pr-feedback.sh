#!/usr/bin/env bash
# pr-feedback.sh [<pr number or URL>] — the PR's review feedback as one JSON object on stdout.
#
# threads   every unresolved review thread, plus resolved ones whose newest comment is from
#           someone other than the operator (a reply most tools miss). Each comment carries
#           `by`: me (the operator, by hand), autofix (posted by Claude Code on the operator's
#           account), bot, or reviewer.
# reviews   submitted reviews with a body, from anyone but the operator.
# comments  PR conversation comments from anyone but the operator, newest 30.
# Bodies are cut to 1500 characters. Exits 1 with {"error": …} on any failure.
set -euo pipefail

die() { jq -n --arg e "$1" '{error: $e}'; exit 1; }
command -v gh >/dev/null && command -v jq >/dev/null || die "needs gh and jq"

pr=$(gh pr view ${1:+"$1"} --json number,url,title,headRefName,headRefOid,baseRefName,author 2>/dev/null) || die "no PR found"
number=$(jq -r .number <<<"$pr")
read -r owner name < <(jq -r '.url | capture("github.com/(?<o>[^/]+)/(?<n>[^/]+)/pull") | "\(.o) \(.n)"' <<<"$pr")
me=$(gh api user --jq .login) || die "gh is not signed in"

threads=$(gh api graphql --paginate -F owner="$owner" -F name="$name" -F number="$number" -f query='
query($owner: String!, $name: String!, $number: Int!, $endCursor: String) {
  repository(owner: $owner, name: $name) { pullRequest(number: $number) {
    reviewThreads(first: 50, after: $endCursor) {
      pageInfo { hasNextPage endCursor }
      nodes { id isResolved isOutdated path line
        comments(last: 30) { nodes { databaseId url createdAt body author { login __typename } } } }
    } } } }' --jq '.data.repository.pullRequest.reviewThreads.nodes[]' | jq -s .) || die "could not fetch review threads"

reviews=$(gh api --paginate "repos/$owner/$name/pulls/$number/reviews" | jq -s 'add // []') || die "could not fetch reviews"
comments=$(gh api --paginate "repos/$owner/$name/issues/$number/comments" | jq -s 'add // []') || die "could not fetch comments"

jq -n --arg me "$me" --argjson pr "$pr" --argjson threads "$threads" --argjson reviews "$reviews" --argjson comments "$comments" '
  def cut: if length > 1500 then .[:1500] + " …[truncated]" else . end;
  def who($login; $type; $body):
    if $login == $me then (if ($body | test("_Generated by \\[Claude Code\\]")) then "autofix" else "me" end)
    elif $type == "Bot" or ($login | test("\\[bot\\]$|^copilot-pull-request-reviewer$|^claude$")) then "bot"
    else "reviewer" end;
  {
    pr: ($pr + {me: $me}),
    threads: [ $threads[]
      | .comments = [ .comments.nodes[] | {id: .databaseId, url, at: .createdAt, author: .author.login,
          by: who(.author.login; .author.__typename; .body), body: (.body | cut)} ]
      | select((.isResolved | not) or .comments[-1].by == "reviewer")
      | {id, resolved: .isResolved, outdated: .isOutdated, path, line, comments} ],
    reviews: [ $reviews[] | select(.user.login != $me and (.body // "") != "")
      | {id, author: .user.login, by: who(.user.login; .user.type; .body), state, at: .submitted_at,
         commit: .commit_id, stale: (.commit_id != $pr.headRefOid), body: (.body | cut)} ],
    comments: ([ $comments[] | select(.user.login != $me)
      | {id, url: .html_url, author: .user.login, by: who(.user.login; .user.type; .body), at: .created_at, body: (.body | cut)} ] | .[-30:])
  }'
